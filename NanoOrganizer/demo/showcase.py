def build_showcase_project(root, *,
                           fractions: Sequence[float] = mat.DEFAULT_FRACTIONS,
                           n_frames: int = 14,
                           n_micrographs: int = 3,
                           image_size: int = 384,
                           tomo_size: int = 128,
                           seed: int = 7,
                           with_images: bool = True,
                           with_tomography: bool = True,
                           include_failed_run: bool = True,
                           overwrite: bool = True) -> Path:
    """Write the multimodal demo project and return its root path.

    Parameters
    ----------
    root : path
        Where to write it.  Created if missing.
    fractions : sequence of float
        Gold atomic fraction of each sample — the hidden control variable.
        One sample is generated per entry.
    n_frames : int
        UV-Vis frames per sample, written as an in-situ growth series.
    n_micrographs : int
        TEM and SEM frames per sample.  ``with_images=False`` skips both, and
        the project then builds without Pillow.
    tomo_size : int
        Edge of the cubic tomogram in voxels.  This is the one large file in
        the project, so it is the first thing to turn down.
    include_failed_run : bool
        Append a synthesis that aborted and has no data at all.
    overwrite : bool
        Replace an existing demo project.  Only ever removes a directory
        carrying the generator's marker file, so pointing this at real data
        cannot delete it.
    """
    root = Path(root).expanduser()
    marker = root / MARKER

    if root.exists() and overwrite:
        if any(root.iterdir()) and not marker.exists():
            raise FileExistsError(
                f"{root} is not empty and was not made by "
                f"build_showcase_project. Choose another path, or delete it "
                f"yourself."
            )
        shutil.rmtree(root)

    root.mkdir(parents=True, exist_ok=True)
    marker.write_text("generated by NanoOrganizer.demo.build_showcase_project\n")

    rng = np.random.default_rng(seed)

    uvvis_root = root / "RawSpectra" / "uvvis_runs"
    uvvis_root.mkdir(parents=True, exist_ok=True)
    axis_path = uvvis_root / "axis_wavelength.npy"
    np.save(axis_path, sig.UVVIS_AXIS)

    synthesis: Dict[str, Dict] = {}
    characterization: Dict[str, Dict] = {}
    testing: Dict[str, Dict] = {}
    computation: Dict[str, Dict] = {}

    for index, x in enumerate(fractions, start=1):
        name = mat.sample_id(index)
        tag = f"b{index:02d}"
        paths: Dict[str, Any] = {}

        _write_uvvis(uvvis_root, tag, x, n_frames, rng)
        paths["uvvis_glob"] = str(uvvis_root / f"uvvis_{tag}_*.npy")
        paths["uvvis_axis"] = str(axis_path)

        paths.update(_write_spectroscopy(root / "Spectroscopy" / name, index, x, rng))
        paths.update(_write_scattering(root / "Scattering" / name, index, x, rng))

        if mat.measured("xpcs", index):
            lag, g2 = sig.xpcs_g2(x, rng)
            paths["xpcs"] = _write_curve(
                root / "Dynamics" / name / "xpcs_g2.dat", lag, g2,
                "lag_time_s", "g2", "XPCS, aggregates in glycerol/water")

        electro = _write_electrochemistry(root / "Electrochemistry" / name, x, rng)
        energy, dos = sig.dft_pdos(x)
        pdos_path = _write_curve(root / "Computation" / name / "pdos.dat",
                                 energy, dos, "E_minus_EF_eV",
                                 "states_per_eV_per_atom",
                                 "surface-layer projected DOS")

        # Folder-convention data: no metadata entry, picked up by the
        # <Modality>Data/<SampleID>/ rule.
        diameters = sig.dls_distribution(x, rng)
        _write_curve(root / "DLSData" / name / "dls_intensity.dat",
                     diameters[0], diameters[1], "diameter_nm", "intensity_pct",
                     "DLS, 173 deg backscatter, intensity-weighted")

        if with_images:
            for frame in range(1, n_micrographs + 1):
                img.write_tiff(root / "TEMData" / name / f"{frame:02d}.tif",
                               img.tem_image(x, image_size, rng),
                               img.TEM_PIXELS_PER_MICRON, "DemoTEM 200 kV")
                img.write_tiff(root / "SEMData" / name / f"{frame:02d}.tif",
                               img.sem_image(x, image_size, rng),
                               img.SEM_PIXELS_PER_MICRON, "DemoSEM 5 kV SE")
            (root / "TEMData" / name / "note.txt").write_text(
                f"{name}: bright-field TEM, nominal x_Au = {x:.2f}\n")

        if with_tomography and mat.measured("tomo", index):
            folder = root / "TomoData" / name
            folder.mkdir(parents=True, exist_ok=True)
            np.save(folder / "tomogram.npy", img.tomo_volume(x, tomo_size, rng))
            (folder / "note.txt").write_text(
                f"reconstructed tomogram, {img.TOMO_NM_PER_VOXEL:.0f} nm voxels\n")

        synthesis[name] = _synthesis_record(index, x)
        characterization[name] = _characterization_record(index, x, paths, n_frames)
        testing[name] = _testing_record(index, x, electro)
        computation[name] = _computation_record(index, x, pdos_path)

    if include_failed_run:
        failed = mat.sample_id(len(fractions) + 1)
        synthesis[failed] = _failed_record(failed, len(fractions) + 1)

    meta = root / "MetaData"
    meta.mkdir(exist_ok=True)
    _write_metadata(meta / "Synthesis_dict.py", "Synthesis_dict",
                    "Colloidal Cu-Au alloy syntheses.", synthesis)
    _write_metadata(meta / "Characterization_dict.py", "Characterization_dict",
                    "Structural, compositional and spectroscopic characterization.",
                    characterization)
    _write_metadata(meta / "Testing_dict.py", "Testing_dict",
                    "CO2-reduction, hydrogen- and oxygen-evolution testing.",
                    testing)
    _write_metadata(meta / "Computation_dict.py", "Computation_dict",
                    "Density-functional calculations on the matching surfaces.",
                    computation)

