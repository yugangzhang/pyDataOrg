def _write_uvvis(folder: Path, tag: str, x: float, n_frames: int,
                 rng) -> List[str]:
    """In-situ growth series: one single-column frame per time point."""
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for time_s, temperature_C, values in sig.uvvis_frames(x, n_frames, rng):
        name = f"uvvis_{tag}_t{int(time_s):05d}s_T{temperature_C:.0f}C.npy"
        np.save(folder / name, values)
        written.append(name)
    return written


def _write_spectroscopy(folder: Path, index: int, x: float, rng) -> Dict[str, Any]:
    """EDS, XPS, Raman, IR and (for some samples) XAS."""
    out: Dict[str, Any] = {}

    energy, counts = sig.eds_spectrum(x, rng)
    out["eds"] = _write_curve(folder / "eds.dat", energy, counts,
                              "energy_keV", "counts",
                              "EDS, 20 kV, silicon drift detector")

    binding, counts = sig.xps_cu2p(x, rng)
    out["xps_cu2p"] = _write_curve(folder / "xps_Cu2p.dat", binding, counts,
                                   "binding_energy_eV", "counts",
                                   "XPS Cu 2p, Al Ka, pass energy 20 eV")
    binding, counts = sig.xps_au4f(x, rng)
    out["xps_au4f"] = _write_curve(folder / "xps_Au4f.dat", binding, counts,
                                   "binding_energy_eV", "counts",
                                   "XPS Au 4f, Al Ka, pass energy 20 eV")

    shift, intensity = sig.raman_spectrum(x, rng)
    out["raman"] = _write_curve(folder / "raman.dat", shift, intensity,
                                "raman_shift_cm-1", "intensity_counts",
                                "Raman, 633 nm, 1 mW, 30 s")

    wavenumber, absorbance = sig.ir_spectrum(x, rng)
    out["ir"] = _write_curve(folder / "ir_seira.dat", wavenumber, absorbance,
                             "wavenumber_cm-1", "absorbance",
                             "ATR-SEIRAS at -1.0 V vs RHE, CO2-saturated")

    if mat.measured("xas", index):
        for state, label in (("as_made", "as-made"), ("reduced", "after 1 h at -1.0 V")):
            energy, mu = sig.xas_spectrum(x, state, rng)
            out[f"xas_{state}"] = _write_curve(
                folder / f"xas_Cu_K_{state}.dat", energy, mu,
                "energy_eV", "normalised_mu", f"Cu K-edge XANES, {label}")
    return out


def _write_scattering(folder: Path, index: int, x: float, rng) -> Dict[str, Any]:
    out: Dict[str, Any] = {}
    q, intensity = sig.saxs_curve(x, rng)
    out["saxs"] = _write_curve(folder / "saxs_1d.dat", q, intensity,
                               "q_invA", "I_q_a.u.",
                               "SAXS, 13.5 keV, 2 m, azimuthally averaged")

    q, intensity = sig.waxs_curve(x, rng)
    out["waxs"] = _write_curve(folder / "waxs_1d.dat", q, intensity,
                               "q_invA", "I_q_a.u.",
                               "WAXS, 13.5 keV, 0.2 m, azimuthally averaged")

    if mat.measured("saxs2d", index):
        names = []
        for frame in range(2):
            pattern = img.saxs2d_pattern(x, 256, rng)
            name = f"saxs2d_{frame:03d}.npy"
            np.save(folder / name, pattern.astype(np.float32))
            names.append(str(folder / name))
        out["saxs2d"] = names
    return out


def _write_electrochemistry(folder: Path, x: float, rng) -> Dict[str, Any]:
    out: Dict[str, Any] = {}

    potential, current = sig.her_lsv(x, rng)
    out["her"] = _write_curve(folder / "her_lsv.dat", potential, current,
                              "potential_V_vs_RHE", "j_mA_cm2",
                              "LSV, Ar-saturated 0.1 M KHCO3, 5 mV/s, iR-corrected")

    potential, current = sig.oer_lsv(x, rng)
    out["oer"] = _write_curve(folder / "oer_lsv.dat", potential, current,
                              "potential_V_vs_RHE", "j_mA_cm2",
                              "LSV, 1 M KOH, 5 mV/s, anodically conditioned film")

    potential, current = sig.co2rr_lsv(x, rng)
    out["co2rr_lsv"] = _write_curve(folder / "co2rr_lsv.dat", potential, current,
                                    "potential_V_vs_RHE", "j_mA_cm2",
                                    "LSV, CO2-saturated 0.1 M KHCO3, 5 mV/s")

    efficiencies = sig.co2rr_faradaic(x, rng)
    files = []
    for product, (potentials, values) in efficiencies.items():
        safe = product.replace("-", "").replace("+", "")
        files.append(_write_curve(
            folder / f"FE_{safe}.dat", potentials, values,
            "potential_V_vs_RHE", "faradaic_efficiency_pct",
            f"{product} by GC/HPLC, 1 h chronoamperometry per point"))
    out["fe_files"] = files
    return out


