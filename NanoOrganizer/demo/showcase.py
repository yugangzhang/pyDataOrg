def _write_curve(path: Path, x: np.ndarray, y: np.ndarray,
                 x_label: str, y_label: str, note: str = "") -> str:
    """Write a two-column text file with a self-describing header."""
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"{x_label}\t{y_label}"
    if note:
        header = f"{note}\n{header}"
    np.savetxt(path, np.column_stack([np.asarray(x), np.asarray(y)]),
               fmt="%.6g", delimiter="\t", header=header)
    return str(path)


def _clean(value: Any) -> Any:
    """Make a value safe to write into a Python source file."""
    if isinstance(value, (np.floating, np.integer)):
        return value.item()
    if isinstance(value, dict):
        return {k: _clean(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_clean(v) for v in value]
    return value


_MODULE_HEADER = '''"""{title}

Generated by ``NanoOrganizer.demo.build_showcase_project`` — edit the
generator, not this file.

The shape is the one the ``sampledict`` ingest adapter expects: a module-level
dict keyed by stable sample ids, each holding nested blocks.  A block that
names files becomes a measurement; every other block is kept verbatim as
filterable parameters.  The dict's own name gives the stage.
"""

'''


def _write_metadata(path: Path, dict_name: str, title: str,
                    records: Dict[str, Dict]) -> None:
    body = pprint.pformat(_clean(records), width=76, sort_dicts=False)
    path.write_text(_MODULE_HEADER.format(title=title)
                    + f"{dict_name} = {body}\n")


