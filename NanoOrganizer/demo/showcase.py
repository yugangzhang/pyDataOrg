#!/usr/bin/env python3
"""
Build the multimodal demo project: a Cu–Au alloy library seen by 15 techniques.

:func:`build_showcase_project` writes a complete, self-consistent campaign to
disk — authored metadata in three stages, raw files in the formats the
instruments would have written, and a deliberately incomplete measurement
matrix.  Everything in it follows from one hidden number per sample, the gold
atomic fraction, so every technique can be checked against every other.

What the project is *for*
-------------------------
It answers the question a new user actually has, which is not "what can this
package do" but "what would I do with my own campaign".  So it contains the
things a real campaign contains and a toy example usually leaves out:

* **two routes in** — measurements declared in metadata, and measurements that
  arrive as a folder someone dropped on the share;
* **three stages** — synthesis, characterization, testing — plus computation,
  because the DFT numbers belong with the sample too;
* **a sparse matrix** — beamtime-limited techniques are on four samples, not
  eight, which is what :meth:`Project.availability` is for;
* **a failed run** — one synthesis aborted and has no data, so the table has a
  row that must be excluded rather than being uniformly tidy;
* **techniques that disagree for a reason** — TEM and DLS report different
  sizes, EDS and XPS report different compositions, and both disagreements are
  physics rather than error.

Nothing is committed to the repository: the project is generated on demand and
can be deleted freely.

>>> from NanoOrganizer.demo import build_showcase_project
>>> root = build_showcase_project("/tmp/CuAuDemo")       # doctest: +SKIP
>>> from NanoOrganizer import open_project               # doctest: +SKIP
>>> wb = open_project(root)                              # doctest: +SKIP
"""

